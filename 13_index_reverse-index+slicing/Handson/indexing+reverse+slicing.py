# Indexing, Reverse Indexing, and Slicing 

s = "Python"

print("String:", s)

# Indexing
print("s[0] =", s[0])   # P
print("s[2] =", s[2])   # t

# Reverse (Negative) Indexing

print("s[-1] =", s[-1]) # n
print("s[-3] =", s[-3]) # h

# Slicing

print("s[0:3] =", s[0:3])   # Pyt
print("s[2:5] =", s[2:5])   # tho
print("s[:4] =", s[:4])     # Pyth
print("s[3:] =", s[3:])     # hon
print("s[::2] =", s[6:1:2])   # Pto

# Reverse String

print("s[::-2] =", s[:5:-2]) # nohtyP